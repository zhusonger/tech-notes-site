/**
 * HTML 文本转义 —— 服务端拼接 HTML 时的唯一来源。
 *
 * 有两个调用方：维护提示页（`maintenance.mjs`）与页面外壳的 SEO 注入（`shell.mjs`）。
 * 两者都要把**数据库里的值**写进 HTML，而库里存的是后台可自由编辑的文本 ——
 * 管理员把站点名填成 `<script>` 时，这个函数是唯一拦住它的东西。
 *
 * 五个字符都要转（含两个引号）：这些值既出现在元素内容里（`<title>`），
 * 也出现在属性值里（`content="…"`）。只转 `<>` 的话，出现在属性位置时
 * 会被值里自带的引号提前闭合，转义等于没做。
 */

const MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }

/** 任意值 → 可安全嵌入 HTML 文本或双引号属性值中的字符串。 */
export const escapeHtml = (text) => String(text ?? '').replace(/[&<>"']/g, (c) => MAP[c])
